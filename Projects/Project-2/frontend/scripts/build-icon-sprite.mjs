/**
 * Generates the inline SVG sprite and its IconName union from installed
 * packages, so the sprite, the type, and what actually renders can never
 * drift apart.
 *
 * Four sources, because they are different kinds of mark:
 *   - Lucide: the 24x24 stroke UI icons. Inherit currentColor, so they take
 *     the surrounding text colour.
 *   - Simple Icons: brand/social marks and payment logos. These are solid
 *     24x24 fill paths — Lucide removed brand icons over trademark concerns,
 *     so they are not available there at any name.
 *   - Logo: this site's own mark (currently just "golf-mark", for F12's
 *     "branding in general" ask — the same glyph as public/favicon.svg).
 *     Fixed brand colours baked into the symbol itself, NOT currentColor —
 *     unlike every other icon here, a logo should look the same wherever
 *     it's placed, not adapt to surrounding text colour.
 *
 * A missing name throws rather than silently emitting a blank symbol: icon
 * sets rename things between versions, and a sprite that quietly loses an
 * icon is far harder to notice than a failed build.
 *
 * Run: node scripts/build-icon-sprite.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as simpleIcons from 'simple-icons';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Lucide names, grouped by where they are used. */
const LUCIDE = [
  // navigation + chrome
  'menu',
  'x',
  'search',
  'chevron-down',
  'chevron-right',
  'chevron-left',
  'arrow-right',
  'arrow-left',
  // commerce
  'shopping-bag',
  'heart',
  'star',
  'ticket-percent',
  'truck',
  'banknote',
  'plus',
  'minus',
  'trash-2',
  'check',
  // account + forms
  'user',
  'circle-user',
  'lock',
  'mail',
  'phone',
  'map-pin',
  'calendar',
  'pencil',
  'eye',
  'upload',
  'sliders-horizontal',
  'store',
  'sparkles',
  'triangle-alert',
];

/** Simple Icons exports, keyed by the name the sprite should expose. */
const BRAND = {
  instagram: 'siInstagram',
  facebook: 'siFacebook',
  youtube: 'siYoutube',
  visa: 'siVisa',
  mastercard: 'siMastercard',
  amex: 'siAmericanexpress',
  paypal: 'siPaypal',
  applepay: 'siApplepay',
  stripe: 'siStripe',
};

/**
 * This site's own mark(s) — raw inner SVG markup, complete with their own
 * fixed stroke/fill colours, pasted in as-is (kept identical to
 * public/favicon.svg so the two never drift). A white ball ringed in the
 * brand's primary ink, on a tee filled with the design system's one
 * accent green.
 *
 * Adapted from "golf-ball-2" on SVG Repo (svgrepo.com, CC0/free-for-
 * commercial-use icons) — geometry theirs, recoloured to match the brand.
 */
const LOGO = {
  'golf-mark':
    '<circle cx="12" cy="9" r="6" fill="#FEFEFE" stroke="#141718" stroke-width="1.5"/>' +
    '<path d="M16 15H8L8.34 15.5A10 10 0 0 1 10 21H14A10 10 0 0 1 15.66 15.5Z" fill="#38CB89"/>',
};

/** Pulls the inner markup out of an <svg> wrapper. */
function innerSvg(markup) {
  const match = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(markup);
  if (!match) throw new Error('Could not parse SVG wrapper');
  return match[1].trim();
}

const symbols = [];

for (const name of LUCIDE) {
  let file;
  try {
    file = readFileSync(join(root, 'node_modules/lucide-static/icons', `${name}.svg`), 'utf8');
  } catch {
    throw new Error(
      `Lucide icon "${name}" not found. Icon sets rename things between ` +
        `versions — check the installed lucide-static rather than assuming.`,
    );
  }
  // Lucide strokes inherit currentColor; the sprite keeps the stroke
  // attributes on the symbol so a <use> renders identically.
  symbols.push(
    `    <symbol id="${name}" viewBox="0 0 24 24" fill="none" ` +
      `stroke="currentColor" stroke-width="2" stroke-linecap="round" ` +
      `stroke-linejoin="round">${innerSvg(file)}</symbol>`,
  );
}

for (const [name, exportName] of Object.entries(BRAND)) {
  const icon = simpleIcons[exportName];
  if (!icon) {
    throw new Error(`Simple Icons export "${exportName}" not found for "${name}".`);
  }
  // Brand marks are solid fills, not strokes.
  symbols.push(
    `    <symbol id="${name}" viewBox="0 0 24 24" fill="currentColor">` +
      `<path d="${icon.path}"/></symbol>`,
  );
}

for (const [name, markup] of Object.entries(LOGO)) {
  // No fill/stroke on the <symbol> itself — every shape carries its own
  // fixed colour, on purpose (see the LOGO comment above).
  symbols.push(`    <symbol id="${name}" viewBox="0 0 24 24" fill="none">${markup}</symbol>`);
}

const names = [...LUCIDE, ...Object.keys(BRAND), ...Object.keys(LOGO)];
const union = names.map((n) => `  | '${n}'`).join('\n');

const output = `// GENERATED by scripts/build-icon-sprite.mjs — do not edit by hand.
// Re-run after changing the icon list: node scripts/build-icon-sprite.mjs
import { Component } from '@angular/core';

/** Every icon in the sprite. Generated, so it cannot drift from the markup. */
export type IconName =
${union};

export const ICON_NAMES: readonly IconName[] = [
${names.map((n) => `  '${n}',`).join('\n')}
];

/**
 * Inline SVG sprite, mounted once at the app root. Rendering an icon is then
 * a <use href="#name"> reference rather than another network request, and
 * every glyph inherits currentColor.
 */
@Component({
  selector: 'icon-sprite',
  template: \`
    <svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">
      <defs>
${symbols.join('\n')}
      </defs>
    </svg>
  \`,
  styles: \`
    :host {
      display: none;
    }
  \`,
})
export class IconSprite {}
`;

writeFileSync(join(root, 'src/app/shared/ui/icon-sprite.ts'), output, 'utf8');
console.log(
  `icon-sprite.ts written — ${LUCIDE.length} Lucide + ${Object.keys(BRAND).length} brand + ` +
    `${Object.keys(LOGO).length} logo = ${names.length} icons`,
);
